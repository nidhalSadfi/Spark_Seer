import { useCallback, useState } from 'react'
import { useSearchParams } from 'react-router-dom'
import { DatabaseZap, RefreshCw } from 'lucide-react'
import { Badge, Card, CardHeader, Notice, PageHeader } from '../components/ui/primitives'
import StatusHeader from '../components/processing/StatusHeader'
import JobList from '../components/processing/JobList'
import JobDrawer from '../components/processing/JobDrawer'
import { useProcessingDatasets, useProcessingJobs, useProcessingStatus } from '../hooks/useProcessing'
import { API_BASE } from '../services/http'
import { fmtInt } from '../utils/format'
import { AI_REVIEW, AI_RULE, fmtUtc, processingUnavailable } from '../utils/processing'

/** Shown instead of the page when /processing/* answers 503 or the API is unreachable. No mock data. */
function NotConnected({ error }) {
  return (
    <Card>
      <div className="flex flex-col items-center gap-3 py-10 text-center">
        <span className="grid size-12 place-items-center rounded-full border border-fire/40 bg-fire/10">
          <DatabaseZap className="size-6 text-fire" aria-hidden />
        </span>
        <h2 className="text-lg font-semibold text-ink">The processing database is not connected</h2>
        <p className="max-w-xl text-sm text-muted">
          {error?.status === 0
            ? `The API at ${API_BASE} did not answer, so there is no processing history to show.`
            : 'The API is running without its PostgreSQL database (for example the public demo deploy, which serves the calendar from a file), so the worker’s jobs, gates and AI reviews cannot be shown here.'}{' '}
          Nothing on this page is simulated: it stays empty until the database is reachable.
        </p>
        {error?.message && <p className="max-w-xl font-mono text-[11px] text-faint">{error.message}</p>}
      </div>
    </Card>
  )
}

function DatasetHistory({ query }) {
  const d = query.data
  if (!d?.datasets?.length) return null
  return (
    <Card>
      <CardHeader kicker="Versions" title="Dataset versions" subtitle="Each approved run publishes a new version; the previous one is superseded." />
      <ul className="flex flex-col gap-2 text-sm">
        {d.datasets.map((v) => (
          <li key={v.id} className="flex flex-wrap items-center gap-2 rounded-xl border border-line bg-sidebar/60 px-3 py-2">
            <span className="font-mono text-xs text-ink">v{v.id}</span>
            <Badge tone={v.status === 'approved' ? 'ok' : 'neutral'}>{v.status}</Badge>
            <span className="text-muted">
              {v.job_id != null ? `job #${v.job_id}` : v.summary?.source ?? 'bootstrap'}
              {Array.isArray(v.summary?.months) && ` · ${v.summary.months.join(', ')}`}
            </span>
            <span className="ml-auto text-xs text-faint">
              {fmtInt(v.current_rows)} current rows · {fmtUtc(v.approved_at ?? v.created_at)}
            </span>
          </li>
        ))}
      </ul>
    </Card>
  )
}

export default function ProcessingPage() {
  const [params, setParams] = useSearchParams()
  const [filters, setFilters] = useState({ kind: 'all', status: 'all', page: 0, pageSize: 20 })
  const status = useProcessingStatus()
  const down = processingUnavailable(status.error)
  const jobs = useProcessingJobs(filters, { enabled: !down })
  const datasets = useProcessingDatasets({ enabled: !down })

  // The open job lives in the URL (?job=4), so a drawer can be linked to and survives a reload.
  const jobParam = params.get('job')
  const jobId = jobParam && /^\d+$/.test(jobParam) ? Number(jobParam) : null
  const openJob = useCallback((id) => setParams((p) => ({ ...Object.fromEntries(p), job: String(id) })), [setParams])
  const closeJob = useCallback(
    () =>
      setParams((p) => {
        const next = Object.fromEntries(p)
        delete next.job
        return next
      }),
    [setParams],
  )

  const now = status.dataUpdatedAt || jobs.dataUpdatedAt || 0

  return (
    <>
      <PageHeader
        kicker="Operations"
        title="Processing Center"
        description="What the worker did with each FIRMS poll: the deterministic steps, the hard gates, the three-agent AI review and what was published. Read-only, refreshed every 30 s."
        actions={
          !down &&
          status.data && (
            <Badge title={`Generated by the API at ${fmtUtc(status.data.generated_at)}`}>
              <RefreshCw className={`size-3 ${status.isFetching ? 'motion-safe:animate-spin' : ''}`} aria-hidden />
              Updated {fmtUtc(status.data.generated_at)}
            </Badge>
          )
        }
      />

      {down ? (
        <NotConnected error={status.error} />
      ) : (
        <div className="flex flex-col gap-4">
          {status.error && <p className="text-sm text-fire-high">Could not load the processing status: {status.error.message}</p>}
          <StatusHeader status={status.data} now={now} onOpenJob={openJob} />
          <JobList query={jobs} filters={filters} setFilters={setFilters} now={now} selectedId={jobId} onOpen={openJob} />
          <DatasetHistory query={datasets} />
          <Notice title="How a run is decided.">
            Hard gates G1-G4 are checked in code first. Then <code>ai_review</code> says what the AI did:{' '}
            <strong>completed</strong>: {AI_REVIEW.completed.text} <strong>unavailable</strong>: {AI_REVIEW.unavailable.text}{' '}
            <strong>disabled</strong>: {AI_REVIEW.disabled.text} {AI_RULE}
          </Notice>
        </div>
      )}

      {!down && <JobDrawer jobId={jobId} onClose={closeJob} />}
    </>
  )
}
